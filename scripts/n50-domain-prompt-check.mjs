/**
 * 본류 프롬프트 도메인 질의 문제 — 실측(읽기전용 SELECT · 원가 0).
 *
 * 가설: `resolveRunPrompts`(packages/audit/runner.ts)가 브랜드명 미입력 시
 *   도메인 문자열을 그대로 brandName으로 써서 프롬프트를 생성·영구저장한다
 *   (`persistFallbackPrompts`). 한 번 저장되면 이후 이름을 고쳐도 재사용만 하고
 *   재생성하지 않는다 → 오래된 브랜드의 Prompt.text에 도메인이 그대로 박혀있을 수 있다.
 *
 * ⚠️ `@repo/database` 는 server-only 라 node 로 직접 못 부른다 → neon 드라이버로 SELECT.
 * 사용: node scripts/n50-domain-prompt-check.mjs
 */
import { readFileSync } from "node:fs";
import { neon } from "@neondatabase/serverless";

const DB_URL_RE = /^DATABASE_URL="?([^"\n]+)"?$/m;

function dbUrl() {
  if (process.env.DATABASE_URL) {
    return process.env.DATABASE_URL;
  }
  for (const f of [
    "../../.env.local",
    "../../apps/app/.env.local",
    ".env.local",
    "apps/app/.env.local",
  ]) {
    try {
      const m = readFileSync(f, "utf8").match(DB_URL_RE);
      if (m) {
        return m[1];
      }
    } catch {
      /* 다음 후보 */
    }
  }
  throw new Error("DATABASE_URL 을 못 찾았다");
}

const sql = neon(dbUrl());

async function main() {
  const brands = await sql`
    SELECT id, name, domain, "createdAt"
    FROM "Brand"
    ORDER BY "createdAt" ASC
  `;
  console.log(`브랜드 총 ${brands.length}건`);

  let suspects = 0;
  for (const b of brands) {
    const domainCore = b.domain.replace(/^https?:\/\//, "").split("/")[0];
    const prompts = await sql`
      SELECT id, text, language, "isAutoGenerated", "createdAt"
      FROM "Prompt"
      WHERE "brandId" = ${b.id}
      ORDER BY "createdAt" ASC
    `;
    const hitsDomain = prompts.filter((p) =>
      p.text.toLowerCase().includes(domainCore.toLowerCase())
    );
    // 브랜드명 자체가 도메인 그대로인 경우(이름칸에 도메인 문자열이 들어간 원조 사고)
    const nameIsDomain =
      b.name.toLowerCase().includes(domainCore.toLowerCase()) ||
      domainCore.toLowerCase().includes(b.name.toLowerCase());

    if (hitsDomain.length > 0 || nameIsDomain) {
      suspects++;
      console.log(
        `\n🔴 brand=${b.id} name="${b.name}" domain=${b.domain} created=${b.createdAt}`
      );
      console.log(`   nameIsDomain=${nameIsDomain}`);
      for (const p of hitsDomain) {
        console.log(
          `   prompt="${p.text}" lang=${p.language} auto=${p.isAutoGenerated} created=${p.createdAt}`
        );
      }
    }
  }
  console.log(`\n의심 브랜드 ${suspects}/${brands.length}건`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

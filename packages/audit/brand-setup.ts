/**
 * 브랜드의 측정 준비도를 DB 에서 읽어 판정한다(2026-10-12).
 *
 * 순수 규칙은 `setup-readiness.ts`. 여기는 값을 읽어 넘기는 얇은 접착층이다 — 러너·cron·관리자 경로가
 * 같은 읽기·같은 규칙을 쓰게 한다(복제 금지).
 *
 * ⛔ 읽기 실패는 측정을 막지 않는다: 실패하면 null 을 돌려주고, 호출부는 판정 없이 진행한다
 *   (준비도는 안내·기록 장치이지 측정의 전제 조건이 아니다 — 필수 3개는 start-tracking 이 따로 지킨다).
 */
import { database, type Industry } from "@repo/database";
import type { MarketScope } from "./market-scope";
import { activePromptFilter, archivedPromptIds } from "./prompt-archive";
import { questionSetKeyOf } from "./question-set-key";
import {
  type BrandSetupReadiness,
  competitorSettingOf,
  getBrandSetupReadiness,
  type SetupReadinessRecord,
  toSetupReadinessRecord,
} from "./setup-readiness";

export interface LoadedBrandSetup {
  brand: {
    domain: string;
    industry: Industry | null;
    marketScope: MarketScope | null;
    name: string;
  };
  readiness: BrandSetupReadiness;
}

const stringList = (value: unknown): string[] =>
  Array.isArray(value)
    ? value.filter((v): v is string => typeof v === "string")
    : [];

export async function loadBrandSetupReadiness(
  brandId: string
): Promise<LoadedBrandSetup | null> {
  try {
    const brand = await database.brand.findUnique({
      where: { id: brandId },
      select: {
        competitors: true,
        domain: true,
        entityVariants: true,
        industry: true,
        marketScope: true,
        name: true,
      },
    });
    if (!brand) {
      return null;
    }
    const archived = await archivedPromptIds([brandId]);
    const savedPrompts = await database.prompt.findMany({
      where: {
        brandId,
        isAutoGenerated: true,
        ...activePromptFilter(archived),
      },
      select: { text: true },
    });
    return {
      brand: {
        domain: brand.domain,
        industry: brand.industry ?? null,
        marketScope: (brand.marketScope as MarketScope | null) ?? null,
        name: brand.name,
      },
      readiness: getBrandSetupReadiness({
        aliases: stringList(brand.entityVariants),
        competitors: competitorSettingOf(brand.competitors),
        domain: brand.domain,
        industry: brand.industry,
        marketScope: brand.marketScope,
        name: brand.name,
        savedPrompts,
      }),
    };
  } catch {
    return null;
  }
}

/** 측정 기록(measurementContext.setupReadiness)용 값을 한 번에 — 읽기 실패면 undefined. */
export async function loadSetupReadinessRecord(
  brandId: string,
  skippedSetup = false
): Promise<SetupReadinessRecord | undefined> {
  const loaded = await loadBrandSetupReadiness(brandId);
  return loaded
    ? toSetupReadinessRecord(loaded.readiness, skippedSetup)
    : undefined;
}

/**
 * 승인된 저장 질문 세트의 지문과 개수. 질문이 없거나 읽기 실패면 undefined(키에 붙이지 않는다).
 * 러너가 측정 시작 때 한 번 읽어 결과에 기록한다(개수는 「20개 중 N개 측정」 표기용).
 */
export async function loadSavedQuestionSet(
  brandId: string
): Promise<{ count: number; key: string } | undefined> {
  try {
    const archived = await archivedPromptIds([brandId]);
    const saved = await database.prompt.findMany({
      where: {
        brandId,
        isAutoGenerated: true,
        ...activePromptFilter(archived),
      },
      select: { text: true },
    });
    const key = questionSetKeyOf(saved.map((p) => p.text));
    return key ? { count: saved.length, key } : undefined;
  } catch {
    return undefined;
  }
}

/** 지문만 필요한 호출부용. */
export async function loadQuestionSetKey(
  brandId: string
): Promise<string | undefined> {
  return (await loadSavedQuestionSet(brandId))?.key;
}

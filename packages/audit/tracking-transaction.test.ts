/**
 * 측정 결과 저장(`persistAuditTracking`) 핫픽스 계약 (2026-10-14).
 *
 * 🔴 사고: 질문마다 `prompt.upsert` 를 interactive 트랜잭션에서 순서대로 돌려, 운영(Supabase 풀러·연결 1개)에서
 *   Prisma 기본 제한 5초를 넘겼다(`audit.tracking.failed` "expired transaction … 5000 ms" ·
 *   "idle-in-transaction timeout"; kakaopay.com c00b3665 이 retry_exhausted 로 부분 적재).
 *
 * 검사하는 것:
 *   ① 질문은 createMany(skipDuplicates) 1번 + id 조회 1번(질문 수와 무관한 왕복) — upsert 를 쓰지 않는다
 *   ② 트랜잭션 제한(timeout/maxWait)을 5초보다 넉넉히 준다
 *   ③ **행 키·매니페스트는 그대로다** (`{jobId}|core|{promptIndex}|{engineId}`, 정렬된 keys)
 *   ④ 멱등: 같은 회차를 다시 써도 행이 늘지 않는다 · 이미 있는 질문은 그대로(skipDuplicates)
 *   ⑤ 질문 id 를 못 찾으면(동시 삭제) 행을 쓰지 않고 "failed"(재시도 대상)
 */
import { beforeEach, describe, expect, it, vi } from "vitest";

interface StoredRow extends Record<string, unknown> {
  trackingRowKey: string | null;
}

const state = {
  trackingRows: [] as StoredRow[],
  prompts: new Map<string, { id: string; isAutoGenerated: boolean }>(),
  promptCreateManyCalls: 0,
  promptFindManyCalls: 0,
  lastPromptCreate: null as null | {
    data: Array<{ isAutoGenerated: boolean; text: string }>;
    skipDuplicates?: boolean;
  },
  txOptions: undefined as undefined | { maxWait?: number; timeout?: number },
  manifest: null as null | {
    brandId: string;
    keys: string[];
    trackedAt: string;
    v: number;
  },
  dropPromptId: false,
};

const tx = {
  prompt: {
    createMany: vi.fn(
      (args: {
        data: Array<{ isAutoGenerated: boolean; text: string }>;
        skipDuplicates?: boolean;
      }) => {
        state.promptCreateManyCalls += 1;
        state.lastPromptCreate = args;
        for (const p of args.data) {
          // skipDuplicates: 이미 있는 (brandId,text) 는 그대로 둔다.
          if (!state.prompts.has(p.text)) {
            state.prompts.set(p.text, {
              id: `prompt_${state.prompts.size + 1}`,
              isAutoGenerated: p.isAutoGenerated,
            });
          }
        }
        return Promise.resolve({ count: args.data.length });
      }
    ),
    findMany: vi.fn((args: { where: { text: { in: string[] } } }) => {
      state.promptFindManyCalls += 1;
      if (state.dropPromptId) {
        return Promise.resolve([]);
      }
      return Promise.resolve(
        args.where.text.in
          .filter((t) => state.prompts.has(t))
          .map((t) => ({ id: state.prompts.get(t)?.id, text: t }))
      );
    }),
  },
  tracking: {
    findMany: vi.fn((args: { where: { trackingRowKey: { in: string[] } } }) =>
      Promise.resolve(
        state.trackingRows.filter((r) =>
          args.where.trackingRowKey.in.includes(r.trackingRowKey as string)
        )
      )
    ),
    createMany: vi.fn(
      ({ data }: { data: StoredRow[]; skipDuplicates?: boolean }) => {
        let created = 0;
        for (const row of data) {
          if (
            row.trackingRowKey &&
            state.trackingRows.some(
              (r) => r.trackingRowKey === row.trackingRowKey
            )
          ) {
            continue; // skipDuplicates
          }
          state.trackingRows.push(row);
          created += 1;
        }
        return Promise.resolve({ count: created });
      }
    ),
  },
  $executeRawUnsafe: vi.fn((_sql: string, ...params: unknown[]) => {
    state.manifest = JSON.parse(params[2] as string);
    return Promise.resolve(1);
  }),
};

vi.mock("@repo/database", () => ({
  database: {
    organization: { findUnique: () => Promise.resolve({ id: "org_1" }) },
    engine: {
      findMany: () => Promise.resolve([{ id: "chatgpt" }, { id: "claude" }]),
    },
    $transaction: vi.fn(
      (
        fn: (t: typeof tx) => Promise<unknown>,
        options?: { maxWait?: number; timeout?: number }
      ) => {
        state.txOptions = options;
        return fn(tx);
      }
    ),
  },
}));
vi.mock("@repo/observability/log", () => ({
  log: { info: vi.fn(), warn: vi.fn(), error: vi.fn() },
}));

const { persistAuditTracking } = await import("./tracking");

type Tagged = Parameters<typeof persistAuditTracking>[0]["tagged"][number];
const row = (over: Partial<Tagged> = {}): Tagged =>
  ({
    engineId: "chatgpt",
    promptText: "질문 A",
    promptLang: "ko",
    promptIndex: 0,
    rawResponse: "답변",
    brandMentioned: true,
    mentionPosition: 1,
    mentionListSize: 5,
    sentiment: "positive",
    citedSources: [],
    shareOfVoice: 0.4,
    isStub: false,
    errorMessage: null,
    ...over,
  }) as Tagged;

const tagged = [
  row({ engineId: "chatgpt", promptText: "질문 A", promptIndex: 0 }),
  row({ engineId: "claude", promptText: "질문 A", promptIndex: 0 }),
  row({ engineId: "chatgpt", promptText: "질문 B", promptIndex: 1 }),
  row({ engineId: "claude", promptText: "질문 B", promptIndex: 1 }),
];

const run = (over: Record<string, unknown> = {}) =>
  persistAuditTracking({
    auditJobId: "job-1",
    brandId: "brand_1",
    completedAt: new Date("2026-10-14T00:00:00.000Z"),
    organizationId: "org_1",
    tagged,
    ...over,
  });

beforeEach(() => {
  state.trackingRows = [];
  state.prompts = new Map();
  state.promptCreateManyCalls = 0;
  state.promptFindManyCalls = 0;
  state.lastPromptCreate = null;
  state.txOptions = undefined;
  state.manifest = null;
  state.dropPromptId = false;
  vi.clearAllMocks();
});

describe("질문 확보 — 왕복이 질문 수와 무관하다", () => {
  it("질문 2개 → createMany 1번 + id 조회 1번 (upsert 없음)", async () => {
    expect(await run()).toBe("completed");
    expect(state.promptCreateManyCalls).toBe(1);
    expect(state.promptFindManyCalls).toBe(1);
    expect(state.lastPromptCreate?.skipDuplicates).toBe(true);
    expect(state.lastPromptCreate?.data.map((p) => p.text)).toEqual([
      "질문 A",
      "질문 B",
    ]);
    expect("upsert" in tx.prompt).toBe(false);
  });

  it("질문이 많아도 질문 쪽 왕복은 그대로 2번", async () => {
    const many = Array.from({ length: 12 }, (_, i) =>
      row({ promptText: `질문 ${i}`, promptIndex: i })
    );
    await run({ tagged: many });
    expect(state.promptCreateManyCalls).toBe(1);
    expect(state.promptFindManyCalls).toBe(1);
  });

  it("축(isAutoGenerated)은 호출부가 정한다 — 기본 true, 브리핑은 false", async () => {
    await run();
    expect(state.lastPromptCreate?.data.every((p) => p.isAutoGenerated)).toBe(
      true
    );
    state.prompts = new Map();
    await run({
      auditJobId: "job-2",
      promptIsAutoGenerated: false,
      trackingAxis: "briefing",
    });
    expect(state.lastPromptCreate?.data.every((p) => !p.isAutoGenerated)).toBe(
      true
    );
  });

  it("이미 있는 질문은 그대로 두고 그 promptId 로 잇는다(시계열 선 안 갈림)", async () => {
    state.prompts.set("질문 A", { id: "existing_A", isAutoGenerated: false });
    await run();
    // skipDuplicates — 기존 질문의 축(false)을 바꾸지 않는다.
    expect(state.prompts.get("질문 A")).toEqual({
      id: "existing_A",
      isAutoGenerated: false,
    });
    const idsForA = state.trackingRows
      .filter((r) => (r.trackingRowKey as string).includes("|0|"))
      .map((r) => r.promptId);
    expect(idsForA).toEqual(["existing_A", "existing_A"]);
  });
});

describe("트랜잭션 제한", () => {
  it("timeout 과 maxWait 를 Prisma 기본 5초보다 넉넉히 준다", async () => {
    await run();
    expect(state.txOptions?.timeout).toBeGreaterThanOrEqual(15_000);
    expect(state.txOptions?.maxWait).toBeGreaterThanOrEqual(5000);
  });
});

describe("행 키·매니페스트·멱등은 그대로다", () => {
  it("행 키 형식 `{jobId}|core|{promptIndex}|{engineId}`", async () => {
    await run();
    expect(state.trackingRows.map((r) => r.trackingRowKey).sort()).toEqual(
      [
        "job-1|core|0|chatgpt",
        "job-1|core|0|claude",
        "job-1|core|1|chatgpt",
        "job-1|core|1|claude",
      ].sort()
    );
  });

  it("매니페스트: v1 · brandId · trackedAt · 정렬된 keys", async () => {
    await run();
    expect(state.manifest).toEqual({
      v: 1,
      brandId: "brand_1",
      trackedAt: "2026-10-14T00:00:00.000Z",
      keys: [
        "job-1|core|0|chatgpt",
        "job-1|core|0|claude",
        "job-1|core|1|chatgpt",
        "job-1|core|1|claude",
      ],
    });
  });

  it("같은 회차를 다시 써도 행이 늘지 않고 같은 매니페스트로 완료한다", async () => {
    await run();
    const firstManifest = JSON.stringify(state.manifest);
    expect(await run()).toBe("completed");
    expect(state.trackingRows).toHaveLength(4);
    expect(JSON.stringify(state.manifest)).toBe(firstManifest);
  });

  it("브리핑 축은 `briefing` 으로 키가 갈라진다", async () => {
    await run({ trackingAxis: "briefing", promptIsAutoGenerated: false });
    expect(
      state.trackingRows.every((r) =>
        (r.trackingRowKey as string).startsWith("job-1|briefing|")
      )
    ).toBe(true);
  });
});

describe("질문 id 를 못 찾으면 행을 쓰지 않는다", () => {
  it("동시 삭제로 id 조회가 비면 failed(재시도 대상), Tracking 행 0", async () => {
    state.dropPromptId = true;
    expect(await run()).toBe("failed");
    expect(state.trackingRows).toHaveLength(0);
    expect(state.manifest).toBeNull();
  });
});

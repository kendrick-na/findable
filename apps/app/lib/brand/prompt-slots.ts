import {
  activePromptFilter,
  archivedPromptIds,
} from "@repo/audit/prompt-archive";
import { planCapabilities } from "@repo/auth/plan";
import { getCurrentPlan } from "@repo/auth/plan-server";
import { database } from "@repo/database";

/** 플랜 상한에서 이미 저장된 추적 질문(보관 제외)을 뺀 남은 칸. */
export async function remainingPromptSlots(brandId: string): Promise<number> {
  const limit = planCapabilities(await getCurrentPlan()).promptLimit;
  const archived = await archivedPromptIds([brandId]);
  const existing = await database.prompt.count({
    where: { brandId, isAutoGenerated: true, ...activePromptFilter(archived) },
  });
  return Math.max(0, limit - existing);
}

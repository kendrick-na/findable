"use server";

import { archivePrompt, restorePrompt } from "@repo/audit/prompt-archive";
import { database } from "@repo/database";
import { parseError } from "@repo/observability/error";
import { log } from "@repo/observability/log";
import { revalidatePath } from "next/cache";
import { hasInFlightMeasurement } from "@/lib/brand/measurement-in-flight";
import { remainingPromptSlots } from "@/lib/brand/prompt-slots";
import { recordQuestionChange } from "@/lib/brand/question-change-log";
import { requireOrg, scopedBrandById } from "@/lib/db/scoped";
import { getAppDictionary } from "@/lib/i18n";

/**
 * 질문 보관·복원 (2026-10-14 · 설계원칙 3). 삭제와 달리 **측정 이력이 남는다** — 질문만 측정 대상에서 빠진다.
 *
 * 🔒 `delete-prompt.ts` 와 같은 불변식: org 는 세션에서 서버가 정하고, 질문의 브랜드가 내 org 소속인지 확인하며,
 *   시스템 기본질문(`isAutoGenerated: false`)은 건드리지 않고, 측정 진행 중에는 막는다.
 * 복원은 플랜 상한의 **남은 칸**이 있을 때만(보관된 질문은 칸을 쓰지 않으니, 되살리면 다시 쓴다).
 */

export type ArchivePromptResult = { ok: true } | { error: string };

const brandErrors = async () => (await getAppDictionary()).brandErrors;

type Owned = { error: string } | { brandId: string; prompt: { text: string } };

async function loadOwnedPrompt(promptId: string): Promise<Owned> {
  const prompt = await database.prompt.findUnique({
    where: { id: promptId },
    select: { id: true, brandId: true, isAutoGenerated: true, text: true },
  });
  if (!prompt) {
    return { error: (await brandErrors()).promptNotFound };
  }
  const brand = await scopedBrandById(prompt.brandId);
  if (!brand) {
    return { error: (await brandErrors()).promptNotFound };
  }
  if (!prompt.isAutoGenerated) {
    return { error: (await brandErrors()).defaultPromptNoEdit };
  }
  if (await hasInFlightMeasurement(brand.id)) {
    return { error: (await brandErrors()).measuringNoEdit };
  }
  return { brandId: brand.id, prompt };
}

async function run(
  promptId: string,
  kind: "archived" | "restored"
): Promise<ArchivePromptResult> {
  try {
    await requireOrg();
  } catch {
    return { error: (await brandErrors()).signInOrg };
  }
  const owned = await loadOwnedPrompt(promptId);
  if ("error" in owned) {
    return owned;
  }
  try {
    if (
      kind === "restored" &&
      (await remainingPromptSlots(owned.brandId)) < 1
    ) {
      return { error: (await brandErrors()).restoreNoRoom };
    }
    const result =
      kind === "archived"
        ? await archivePrompt(promptId)
        : await restorePrompt(promptId);
    if (!result.ok) {
      return { error: (await brandErrors()).archiveUnavailable };
    }
    log.info(`brand.prompt.${kind}`, { brandId: owned.brandId, promptId });
    await recordQuestionChange(owned.brandId, {
      kind,
      text: owned.prompt.text,
    });
    revalidatePath("/prompts");
    return { ok: true };
  } catch (error) {
    log.error(`brand.prompt.${kind}_failed`, {
      brandId: owned.brandId,
      promptId,
      error: parseError(error),
    });
    return { error: (await brandErrors()).archiveFailed };
  }
}

export const archivePromptAction = (input: { promptId: string }) =>
  run(input.promptId, "archived");

export const restorePromptAction = (input: { promptId: string }) =>
  run(input.promptId, "restored");

import koDict from "@repo/internationalization/dictionaries/ko.json";
import { cleanup, fireEvent, render, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const h = vi.hoisted(() => ({
  archive: vi.fn(),
  restore: vi.fn(),
  inFlight: vi.fn(),
  slots: vi.fn(),
  findUnique: vi.fn(),
  create: vi.fn(),
  del: vi.fn(),
  update: vi.fn(),
  trackingCount: vi.fn(),
  record: vi.fn(),
}));

vi.mock("next/navigation", () => ({
  useRouter: () => ({ push: vi.fn(), refresh: vi.fn() }),
}));
vi.mock("next/cache", () => ({ revalidatePath: vi.fn() }));
vi.mock("@repo/audit/prompt-archive", () => ({
  archivePrompt: h.archive,
  restorePrompt: h.restore,
}));
vi.mock("@repo/database", () => ({
  database: {
    prompt: {
      findUnique: h.findUnique,
      create: h.create,
      delete: h.del,
      update: h.update,
    },
    tracking: { count: h.trackingCount },
  },
}));
vi.mock("@/lib/db/scoped", () => ({
  requireOrg: () => Promise.resolve("org_1"),
  scopedBrandById: () => Promise.resolve({ id: "brand_1" }),
}));
vi.mock("@/lib/brand/measurement-in-flight", () => ({
  hasInFlightMeasurement: h.inFlight,
}));
vi.mock("@/lib/brand/prompt-slots", () => ({ remainingPromptSlots: h.slots }));
vi.mock("@/lib/brand/question-change-log", () => ({
  recordQuestionChange: h.record,
}));
vi.mock("@repo/observability/log", () => ({
  log: { info: vi.fn(), warn: vi.fn(), error: vi.fn() },
}));
vi.mock("@repo/observability/error", () => ({ parseError: String }));

import { ArchivedPromptList } from "../app/(authenticated)/prompts/archived-prompt-list";
import { PromptList } from "../app/(authenticated)/prompts/prompt-list";
import {
  archivePromptAction,
  restorePromptAction,
} from "../app/actions/brand/archive-prompt";
import { editPromptAction } from "../app/actions/brand/edit-prompt";

const OWNED = {
  id: "p1",
  brandId: "brand_1",
  isAutoGenerated: true,
  text: "기존 질문",
  language: "ko",
  category: "recommendation",
};

beforeEach(() => {
  for (const fn of Object.values(h)) {
    fn.mockReset();
  }
  h.findUnique.mockResolvedValue(OWNED);
  h.inFlight.mockResolvedValue(false);
  h.slots.mockResolvedValue(3);
  h.archive.mockResolvedValue({ ok: true });
  h.restore.mockResolvedValue({ ok: true });
  h.create.mockResolvedValue({ id: "p2" });
  h.record.mockResolvedValue(undefined);
});
afterEach(cleanup);

describe("archivePromptAction / restorePromptAction", () => {
  it("보관하면 질문은 지우지 않고(삭제 호출 0) 변경 이력을 남긴다", async () => {
    expect(await archivePromptAction({ promptId: "p1" })).toEqual({ ok: true });
    expect(h.archive).toHaveBeenCalledWith("p1");
    expect(h.del).not.toHaveBeenCalled();
    expect(h.record).toHaveBeenCalledWith("brand_1", {
      kind: "archived",
      text: "기존 질문",
    });
  });

  it("시스템 기본질문은 보관하지 못한다", async () => {
    h.findUnique.mockResolvedValue({ ...OWNED, isAutoGenerated: false });
    expect(await archivePromptAction({ promptId: "p1" })).toHaveProperty(
      "error"
    );
    expect(h.archive).not.toHaveBeenCalled();
  });

  it("측정 진행 중에는 막는다", async () => {
    h.inFlight.mockResolvedValue(true);
    expect(await archivePromptAction({ promptId: "p1" })).toHaveProperty(
      "error"
    );
    expect(h.archive).not.toHaveBeenCalled();
  });

  it("컬럼이 아직 없으면(no_column) 정직한 오류 — 아무것도 바뀌지 않는다", async () => {
    h.archive.mockResolvedValue({ ok: false, reason: "no_column" });
    const result = await archivePromptAction({ promptId: "p1" });
    expect(result).toEqual({
      error: koDict.app.brandErrors.archiveUnavailable,
    });
    expect(h.record).not.toHaveBeenCalled();
  });

  it("복원은 남은 칸이 있을 때만", async () => {
    h.slots.mockResolvedValue(0);
    expect(await restorePromptAction({ promptId: "p1" })).toEqual({
      error: koDict.app.brandErrors.restoreNoRoom,
    });
    expect(h.restore).not.toHaveBeenCalled();
    h.slots.mockResolvedValue(1);
    expect(await restorePromptAction({ promptId: "p1" })).toEqual({ ok: true });
    expect(h.restore).toHaveBeenCalledWith("p1");
  });
});

describe("editPromptAction — 측정 기록이 있으면 새 질문 + 기존 보관", () => {
  beforeEach(() => {
    h.findUnique.mockImplementation((args: { where: { id?: string } }) =>
      Promise.resolve(args.where.id ? OWNED : null)
    );
  });

  it("기록이 있으면 새 질문을 만들고 기존 질문을 보관한다(제자리 수정 안 함)", async () => {
    h.trackingCount.mockResolvedValue(5);
    expect(await editPromptAction({ promptId: "p1", text: "새 문장" })).toEqual(
      {
        ok: true,
      }
    );
    expect(h.create.mock.calls[0]?.[0].data).toMatchObject({
      brandId: "brand_1",
      text: "새 문장",
      language: "ko",
      category: "recommendation",
      isAutoGenerated: true,
    });
    expect(h.archive).toHaveBeenCalledWith("p1");
    expect(h.update).not.toHaveBeenCalled();
  });

  it("기록이 없으면 잃을 게 없어 제자리 수정", async () => {
    h.trackingCount.mockResolvedValue(0);
    h.update.mockResolvedValue({});
    await editPromptAction({ promptId: "p1", text: "새 문장" });
    expect(h.update).toHaveBeenCalledTimes(1);
    expect(h.create).not.toHaveBeenCalled();
  });

  it("보관에 실패하면 새로 만든 질문을 되돌리고 제자리 수정으로 물러난다", async () => {
    h.trackingCount.mockResolvedValue(5);
    h.archive.mockResolvedValue({ ok: false, reason: "no_column" });
    h.update.mockResolvedValue({});
    h.del.mockResolvedValue({});
    expect(await editPromptAction({ promptId: "p1", text: "새 문장" })).toEqual(
      {
        ok: true,
      }
    );
    expect(h.del).toHaveBeenCalledWith({ where: { id: "p2" } });
    expect(h.update).toHaveBeenCalledTimes(1);
  });
});

describe("화면", () => {
  const PROMPT = {
    id: "p1",
    text: "우리 브랜드 어때?",
    language: "ko",
    category: null,
    measuredCount: 5,
  };

  it("보관 버튼이 있고, 누르면 보관 액션을 부른다", async () => {
    const onArchive = vi.fn().mockResolvedValue({ ok: true });
    const screen = render(
      <PromptList
        onArchive={onArchive}
        prompts={[PROMPT]}
        t={koDict.app.promptList}
      />
    );
    fireEvent.click(
      screen.getByRole("button", { name: "우리 브랜드 어때? 보관" })
    );
    await waitFor(() =>
      expect(onArchive).toHaveBeenCalledWith({ promptId: "p1" })
    );
  });

  it("보관 실행자가 없으면 보관 버튼을 그리지 않는다", () => {
    const screen = render(
      <PromptList prompts={[PROMPT]} t={koDict.app.promptList} />
    );
    expect(screen.queryByRole("button", { name: /보관/ })).toBeNull();
  });

  it("삭제 확인 문구는 '보관하면 기록이 남는다'를 알려 준다", () => {
    const screen = render(
      <PromptList
        onArchive={vi.fn()}
        onDelete={vi.fn()}
        prompts={[PROMPT]}
        t={koDict.app.promptList}
      />
    );
    fireEvent.click(
      screen.getByRole("button", { name: "우리 브랜드 어때? 삭제" })
    );
    screen.getByText(/기록을 남기려면 보관하세요/);
  });

  it("보관한 질문 목록에서 복원하면 복원 액션을 부른다", async () => {
    const onRestore = vi.fn().mockResolvedValue({ ok: true });
    const screen = render(
      <ArchivedPromptList
        onRestore={onRestore}
        prompts={[{ id: "p9", text: "예전 질문", measuredCount: 3 }]}
        t={koDict.app.promptList}
      />
    );
    screen.getByText("보관한 질문");
    fireEvent.click(screen.getByRole("button", { name: "예전 질문 복원" }));
    await waitFor(() =>
      expect(onRestore).toHaveBeenCalledWith({ promptId: "p9" })
    );
  });

  it("보관한 질문이 없으면 아무것도 그리지 않는다", () => {
    const screen = render(
      <ArchivedPromptList
        onRestore={vi.fn()}
        prompts={[]}
        t={koDict.app.promptList}
      />
    );
    expect(screen.container.innerHTML).toBe("");
  });
});

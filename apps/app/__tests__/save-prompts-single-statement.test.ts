/**
 * 추적 질문 저장은 **단일 SQL**이다 — 20개 저장이 5초 트랜잭션 제한에 걸려 전부 실패하던 운영 사고(2026-10-13).
 *
 * 🔴 사고: 질문마다 upsert 를 interactive `$transaction` 안에서 순서대로 돌렸다. 운영(Supabase 풀러·연결 1개)에서는
 *   20개가 Prisma 기본 제한 5초를 넘겼다(로그: "expired transaction … 5000 ms, 5732 ms passed").
 *   → 온보딩 5단계 [다음]이 "프롬프트 저장 중 문제가 발생했습니다"로 실패, 저장 0건.
 *
 * @vitest-environment node
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { beforeEach, describe, expect, it, vi } from "vitest";

const h = vi.hoisted(() => ({
  createMany: vi.fn(),
  count: vi.fn(),
  transaction: vi.fn(),
  plan: vi.fn(),
}));

vi.mock("@repo/database", () => ({
  database: {
    $transaction: h.transaction,
    prompt: { count: h.count, createMany: h.createMany },
  },
}));
vi.mock("@repo/auth/plan-server", () => ({ getCurrentPlan: h.plan }));
vi.mock("@/lib/db/scoped", () => ({
  requireOrg: () => Promise.resolve("org_1"),
  scopedBrandById: () => Promise.resolve({ id: "brand_1" }),
}));
vi.mock("@repo/observability/log", () => ({
  log: { info: vi.fn(), warn: vi.fn(), error: vi.fn() },
}));
vi.mock("@repo/observability/error", () => ({ parseError: String }));
vi.mock("@repo/ai/lib/brand-identity", () => ({
  lookupStaticBrandName: vi.fn(),
  resolveBrandIdentity: vi.fn(),
}));
vi.mock("@repo/ai/lib/prompt-suggestions", async (importOriginal) => ({
  ...(await importOriginal<object>()),
  suggestTrackingPrompts: vi.fn(),
}));

import { saveApprovedPromptsAction } from "../app/actions/brand/suggest-prompts";

const twenty = Array.from({ length: 20 }, (_, i) => ({
  category: "competitor" as const,
  language: "ko" as const,
  text: `수분 크림 질문 ${i} 추천해줘`,
  topic: "best_in_category" as const,
}));

beforeEach(() => {
  for (const fn of Object.values(h)) {
    fn.mockReset();
  }
  h.plan.mockResolvedValue("growth");
  h.count.mockResolvedValue(0);
  h.createMany.mockResolvedValue({ count: 20 });
});

describe("saveApprovedPromptsAction — 단일 문장 저장", () => {
  it("20개를 interactive 트랜잭션 없이 createMany 한 번으로 저장한다", async () => {
    const result = await saveApprovedPromptsAction({
      brandId: "brand_1",
      prompts: twenty,
    });
    expect(result).toMatchObject({ ok: true, saved: 20 });
    expect(h.transaction).not.toHaveBeenCalled();
    expect(h.createMany).toHaveBeenCalledTimes(1);
    const arg = h.createMany.mock.calls[0]?.[0];
    expect(arg.skipDuplicates).toBe(true);
    expect(arg.data).toHaveLength(20);
    expect(arg.data[0]).toMatchObject({
      brandId: "brand_1",
      isAutoGenerated: true,
      category: "best_in_category",
      language: "ko",
    });
  });

  it("이미 있는 질문은 건드리지 않는다(skipDuplicates = 예전 upsert update:{} 와 같은 뜻)", async () => {
    await saveApprovedPromptsAction({ brandId: "brand_1", prompts: twenty });
    expect(h.createMany.mock.calls[0]?.[0].skipDuplicates).toBe(true);
  });

  it("플랜 상한을 넘으면 상한까지만 저장하고 capped 로 알린다", async () => {
    h.plan.mockResolvedValue("free"); // 상한 5
    h.createMany.mockResolvedValue({ count: 5 });
    const result = await saveApprovedPromptsAction({
      brandId: "brand_1",
      prompts: twenty,
    });
    expect(h.createMany.mock.calls[0]?.[0].data).toHaveLength(5);
    expect(result).toMatchObject({
      ok: true,
      saved: 5,
      capped: true,
      requested: 20,
      limit: 5,
    });
  });

  it("저장이 실패하면 성공처럼 말하지 않고 오류를 돌려준다", async () => {
    h.createMany.mockRejectedValue(new Error("db down"));
    const result = await saveApprovedPromptsAction({
      brandId: "brand_1",
      prompts: twenty,
    });
    expect("error" in result && result.error).toContain("저장 중 문제");
  });
});

describe("소스 계약 — 질문 저장 경로에 interactive 트랜잭션을 되살리지 않는다", () => {
  it("saveApprovedPromptsAction 이 있는 파일에 $transaction 이 없다", () => {
    const source = readFileSync(
      join(process.cwd(), "app/actions/brand/suggest-prompts.ts"),
      "utf8"
    );
    expect(source).not.toContain("database.$transaction");
    expect(source).toContain("createMany");
  });
});
